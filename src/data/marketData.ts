const generateCandlesticks = (basePrice: number, count: number = 30): CandlestickBar[] => {
  const bars: CandlestickBar[] = [];
  let currentPrice = basePrice * 0.92;

  for (let i = 0; i < count; i++) {
    const volatility = basePrice * 0.015;
    const change = (Math.random() - 0.48) * volatility;
    const open = currentPrice;
    const close = Math.max(1, open + change);
    const high = Math.max(open, close) + Math.random() * (volatility * 0.5);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.5);
    const volume = Math.floor(10000000 + Math.random() * 25000000);

    const time = `${9 + Math.floor(i / 3)}:${(i % 3) * 20 === 0 ? "00" : (i % 3) * 20}`;

    bars.push({
      time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last bar close matches current base price
  if (bars.length > 0) {
    bars[bars.length - 1].close = basePrice;
  }

  return bars;
};

